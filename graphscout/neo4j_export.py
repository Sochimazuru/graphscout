"""Optional: mirror the RDF graph into Neo4j.

Always writes outputs/graph.cypher (paste it into Neo4j Browser, or run it with
cypher-shell). If NEO4J_URI is set and the `neo4j` package is installed, it also
pushes the graph directly.
"""
from __future__ import annotations

import json
import os
import re
from collections import defaultdict

from rdflib import Graph
from rdflib.namespace import PROV, RDF, RDFS, SKOS

from .config import Config
from .schema import KG, RELATION_DESCRIPTIONS, SDO


def _rel_type(prop: str) -> str:
    return re.sub(r"([a-z])([A-Z])", r"\1_\2", prop).upper()


def _local(uri) -> str:
    return str(uri).replace(str(KG), "")


def collect(g: Graph) -> tuple[list[dict], list[dict]]:
    nodes = []
    for p in g.subjects(RDF.type, KG.Paper):
        nodes.append({"id": _local(p), "label": "Paper", "name": str(g.value(p, RDFS.label) or ""),
                      "url": str(g.value(p, SDO.url) or "")})
    for cls in ["Method", "Task", "Dataset", "Metric", "Model", "Concept"]:
        for e in g.subjects(RDF.type, KG[cls]):
            nodes.append({"id": _local(e), "label": cls, "name": str(g.value(e, RDFS.label) or ""),
                          "aliases": sorted(str(a) for a in g.objects(e, SKOS.altLabel))})

    sources = defaultdict(set)
    originals = defaultdict(set)
    for st in g.subjects(RDF.type, RDF.Statement):
        key = (g.value(st, RDF.subject), g.value(st, RDF.predicate), g.value(st, RDF.object))
        for src in g.objects(st, PROV.wasDerivedFrom):
            sources[key].add(_local(src))
        for o in g.objects(st, KG.originalRelation):
            originals[key].add(str(o))

    edges = []
    for prop in RELATION_DESCRIPTIONS:
        for s, o in g.subject_objects(KG[prop]):
            key = (s, KG[prop], o)
            edges.append({"from": _local(s), "to": _local(o), "type": _rel_type(prop),
                          "sources": sorted(sources[key]), "original": sorted(originals[key])})
    for s, o in g.subject_objects(KG.mentions):
        edges.append({"from": _local(s), "to": _local(o), "type": "MENTIONS", "sources": [], "original": []})
    return nodes, edges


def to_cypher(nodes: list[dict], edges: list[dict]) -> str:
    q = json.dumps
    lines = ["// Generated by GraphScout. Run in Neo4j Browser or cypher-shell.",
             "CREATE CONSTRAINT node_id IF NOT EXISTS FOR (n:Node) REQUIRE n.id IS UNIQUE;"]
    for n in nodes:
        props = f"n.name = {q(n['name'])}"
        if n.get("url"):
            props += f", n.url = {q(n['url'])}"
        if n.get("aliases"):
            props += f", n.aliases = {q(n['aliases'])}"
        lines.append(f"MERGE (n:Node {{id: {q(n['id'])}}}) SET n:{n['label']}, {props};")
    for e in edges:
        lines.append(
            f"MATCH (a:Node {{id: {q(e['from'])}}}), (b:Node {{id: {q(e['to'])}}}) "
            f"MERGE (a)-[r:{e['type']}]->(b) SET r.sources = {q(e['sources'])}, r.original = {q(e['original'])};"
        )
    return "\n".join(lines) + "\n"


def export(g: Graph, cfg: Config) -> str:
    nodes, edges = collect(g)
    path = cfg.out_dir / "graph.cypher"
    path.write_text(to_cypher(nodes, edges), encoding="utf-8")
    msg = f"Wrote {path} ({len(nodes)} nodes, {len(edges)} relationships)."
    uri = os.getenv("NEO4J_URI")
    if uri:
        msg += "\n" + push(nodes, edges, uri)
    return msg


def push(nodes: list[dict], edges: list[dict], uri: str) -> str:
    try:
        from neo4j import GraphDatabase
    except ImportError:
        return "NEO4J_URI is set but the `neo4j` package is missing: pip install neo4j"
    auth = (os.getenv("NEO4J_USER", "neo4j"), os.getenv("NEO4J_PASSWORD", "neo4j"))
    with GraphDatabase.driver(uri, auth=auth) as driver, driver.session() as session:
        session.run("CREATE CONSTRAINT node_id IF NOT EXISTS FOR (n:Node) REQUIRE n.id IS UNIQUE")
        by_label = defaultdict(list)
        for n in nodes:
            by_label[n["label"]].append(n)
        for label, batch in by_label.items():
            session.run(
                f"UNWIND $rows AS row MERGE (n:Node {{id: row.id}}) SET n:{label}, n.name = row.name, "
                "n.url = row.url, n.aliases = row.aliases",
                rows=[{"id": n["id"], "name": n["name"], "url": n.get("url"), "aliases": n.get("aliases", [])}
                      for n in batch],
            )
        by_type = defaultdict(list)
        for e in edges:
            by_type[e["type"]].append(e)
        for rtype, batch in by_type.items():
            session.run(
                f"UNWIND $rows AS row MATCH (a:Node {{id: row.from}}), (b:Node {{id: row.to}}) "
                f"MERGE (a)-[r:{rtype}]->(b) SET r.sources = row.sources, r.original = row.original",
                rows=batch,
            )
    return f"Pushed {len(nodes)} nodes and {len(edges)} relationships to {uri}."
